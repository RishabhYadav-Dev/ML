"""**# Implementing Boosting (AdaBoostClassifier)**"""

from sklearn.ensemble import BaggingClassifier, AdaBoostClassifier
from sklearn.tree import DecisionTreeClassifier

# Implementing Boosting (AdaBoostClassifier)
# The base learner will be a decision tree with depth = 2
tree_adaboost = DecisionTreeClassifier(max_depth=2, random_state=42)

# AdaBoost initialization
# It's defined the decision tree as the base learner (updated from base_estimator)
# The number of estimators will be 10
# The learning rate controls the contribution of each weak learner
adaboost_iris = AdaBoostClassifier(estimator=tree_adaboost, n_estimators=10, learning_rate=0.1, random_state=42)

# Train!
adaboost_iris.fit(X_train, y_train)

# Evaluation
print(f"AdaBoost Train score: {adaboost_iris.score(X_train, y_train):.4f}")
print(f"AdaBoost Test score: {adaboost_iris.score(X_test, y_test):.4f}")

