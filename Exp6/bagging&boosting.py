df = pd.read_csv("/content/iris.csv")

"""**# Implementing Bagging (BaggingClassifier)**"""

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

# Feature selection and train-test split
X = df.iloc[:, :-1]
y = df.iloc[:, -1]
# Note: If your CSV includes an 'Id' column as the first column, use: X = df.iloc[:, 1:-1]
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

# Implementing Bagging (BaggingClassifier)
# For simplicity, we are going to use as base estimator a Decision Tree with fixed parameters.
# Using max_depth=2 to prevent overfitting on this relatively simple dataset.
tree_bagging = DecisionTreeClassifier(max_depth=2, random_state=42)

# The bagging ensemble classifier is initialized with:
# estimator = DecisionTree (updated from base_estimator)
# n_estimators = 10 : number of base estimators in the ensemble
# max_samples = 0.8 : it's gonna be taken randomly 80% of items with replacement
# bootstrap = True : means that the sampling is gonna be with replacement
bagging_iris = BaggingClassifier(estimator=tree_bagging, n_estimators=10, max_samples=0.8, bootstrap=True, random_state=42)

# Training
bagging_iris.fit(X_train, y_train)

# Evaluating
print(f"Bagging Train score: {bagging_iris.score(X_train, y_train):.4f}")
